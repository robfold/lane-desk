let lang = 'en';

/** 'ko-KR', 'ko' → 'ko'; anything else → 'en'. */
function pick(locale) {
  return /^ko\b/i.test(String(locale || '')) ? 'ko' : 'en';
}

function setLang(l) {
  lang = STRINGS[l] ? l : 'en';
}

function getLang() {
  return lang;
}

/** Look up a string and fill {name} slots. A missing key falls back to English, then to the key. */
function t(key, vars) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k]))) : s;
}

/** The whole table for the current language, for the window. */
function table() {
  return { ...STRINGS.en, ...STRINGS[lang] };
}

module.exports = { STRINGS, pick, setLang, getLang, t, table };
